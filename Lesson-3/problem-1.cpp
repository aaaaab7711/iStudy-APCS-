#include <iostream>
using namespace std;

int main()
{
    int N;
    cin >> N;

    int H = N / 3600;
    N %= 3600;

    int M = N / 60;
    int S = N % 60;

    cout << H << " 小時 "
         << M << " 分鐘 "
         << S << " 秒";

    return 0;
}

