#include <iostream>
using namespace std;

int main()
{

    // ========================================
    // 1. AND (&)
    // ========================================

    int a = 5; // Binary: 0101
    int b = 3; // Binary: 0011

    cout << "===== AND (&) =====" << endl;

    cout << "5 & 3 = " << (a & b) << endl;

    //   0101
    // & 0011
    // -------
    //   0001
    // Result: 1

    // ========================================
    // 2. OR (|)
    // ========================================

    cout << "\n===== OR (|) =====" << endl;

    cout << "5 | 3 = " << (a | b) << endl;

    //   0101
    // | 0011
    // -------
    //   0111
    // Result: 7

    // ========================================
    // 3. XOR (^)
    // ========================================

    cout << "\n===== XOR (^) =====" << endl;

    cout << "5 ^ 3 = " << (a ^ b) << endl;

    //   0101
    // ^ 0011
    // -------
    //   0110
    // Result: 6

    // XOR 的重要特性

    cout << "\nXOR Properties:" << endl;

    cout << "5 ^ 5 = " << (5 ^ 5) << endl;
    // 相同的數 XOR → 0

    cout << "5 ^ 0 = " << (5 ^ 0) << endl;
    // 任何數 XOR 0 → 自己

    // ========================================
    // 4. NOT (~)
    // ========================================

    cout << "\n===== NOT (~) =====" << endl;

    cout << "~5 = " << (~5) << endl;

    // ~ 會將所有 bit 反轉
    // 000...0101
    // ↓↓↓↓↓↓↓↓↓
    // 111...1010
    //
    // 注意：C++ int 通常使用 32 bits
    // 所以 ~5 的結果通常是 -6

    // ========================================
    // 5. Left Shift (<<)
    // ========================================

    cout << "\n===== Left Shift (<<) =====" << endl;

    cout << "1 << 1 = " << (1 << 1) << endl;
    cout << "1 << 2 = " << (1 << 2) << endl;
    cout << "1 << 3 = " << (1 << 3) << endl;
    cout << "1 << 4 = " << (1 << 4) << endl;

    // 1 << k
    //
    // 0001
    // ↓
    // 0010  = 2
    //
    // 0001
    // ↓↓
    // 0100  = 4
    //
    // 0001
    // ↓↓↓
    // 1000  = 8

    // ========================================
    // 6. Right Shift (>>)
    // ========================================

    cout << "\n===== Right Shift (>>) =====" << endl;

    cout << "16 >> 1 = " << (16 >> 1) << endl;
    cout << "16 >> 2 = " << (16 >> 2) << endl;
    cout << "16 >> 3 = " << (16 >> 3) << endl;

    // 16 = 10000
    //
    // 10000 >> 1 = 01000 = 8
    // 10000 >> 2 = 00100 = 4
    // 10000 >> 3 = 00010 = 2

    // ========================================
    // 7. AND 應用：判斷奇偶數
    // ========================================

    cout << "\n===== Check Even / Odd =====" << endl;

    int num = 7;

    if (num & 1)
    {
        cout << num << " is Odd" << endl;
    }
    else
    {
        cout << num << " is Even" << endl;
    }

    // 偶數最後一個 bit 是 0
    // 奇數最後一個 bit 是 1
    //
    // 7 = 0111
    //
    // 0111
    // &0001
    // -----
    // 0001 → Odd

    // ========================================
    // 8. Check the k-th Bit
    // ========================================

    cout << "\n===== Check k-th Bit =====" << endl;

    num = 13;
    int k = 2;

    // 13 = 1101
    //
    // 第 2 個 bit：
    //
    // 1101
    // 0100
    // ----
    // 0100 → 不為 0
    //
    // 所以第 2 個 bit 是 1

    if (num & (1 << k))
    {
        cout << "Bit " << k << " is 1" << endl;
    }
    else
    {
        cout << "Bit " << k << " is 0" << endl;
    }

    // ========================================
    // 9. Set k-th Bit
    // ========================================

    cout << "\n===== Set k-th Bit =====" << endl;

    num = 8;
    k = 1;

    // 8 = 1000
    //
    // 1 << 1 = 0010
    //
    // 1000
    // |0010
    // ----
    // 1010 = 10

    num = num | (1 << k);

    cout << "Result = " << num << endl;

    // ========================================
    // 10. Clear k-th Bit
    // ========================================

    cout << "\n===== Clear k-th Bit =====" << endl;

    num = 15;
    k = 2;

    // 15 = 1111
    //
    // 1 << 2 = 0100
    //
    // ~(0100) = 1011
    //
    // 1111
    // &1011
    // ----
    // 1011 = 11

    num = num & ~(1 << k);

    cout << "Result = " << num << endl;

    // ========================================
    // 11. Toggle k-th Bit
    // ========================================

    cout << "\n===== Toggle k-th Bit =====" << endl;

    num = 10;
    k = 1;

    // 10 = 1010
    //
    // 1 << 1 = 0010
    //
    // 1010
    // ^0010
    // ----
    // 1000 = 8

    num = num ^ (1 << k);

    cout << "Result = " << num << endl;

    // ========================================
    // 12. XOR Application
    //     Find the Single Number
    // ========================================

    cout << "\n===== Single Number =====" << endl;

    int nums[] = {4, 1, 2, 1, 2};
    int n = 5;

    int answer = 0;

    for (int i = 0; i < n; i++)
    {
        answer ^= nums[i];
    }

    cout << "Single number = " << answer << endl;

    // 4 ^ 1 ^ 2 ^ 1 ^ 2
    //
    // = 4 ^ (1 ^ 1) ^ (2 ^ 2)
    //
    // = 4 ^ 0 ^ 0
    //
    // = 4

    // ========================================
    // 13. n & (n - 1)
    //     Remove the rightmost 1
    // ========================================

    cout << "\n===== Remove Rightmost 1 =====" << endl;

    num = 12;

    // 12 = 1100
    // 11 = 1011
    //
    // 1100
    // &1011
    // ----
    // 1000
    //
    // 最右邊的 1 被消掉

    cout << "12 & 11 = " << (num & (num - 1)) << endl;

    // ========================================
    // 14. Power of Two
    // ========================================

    cout << "\n===== Power of Two =====" << endl;

    num = 16;

    if (num > 0 && (num & (num - 1)) == 0)
    {
        cout << num << " is a power of two" << endl;
    }
    else
    {
        cout << num << " is NOT a power of two" << endl;
    }

    // ========================================
    // 15. Count Set Bits
    // ========================================

    cout << "\n===== Count Set Bits =====" << endl;

    num = 13;

    int count = 0;

    while (num > 0)
    {

        // 檢查最後一個 bit
        if (num & 1)
        {
            count++;
        }

        // 向右移一位
        num >>= 1;
    }

    cout << "Number of 1 bits = " << count << endl;

    // 13 = 1101
    //
    // 有三個 1
    //
    // Answer = 3

    return 0;
}

