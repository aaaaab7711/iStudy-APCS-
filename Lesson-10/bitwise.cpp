// num & (1 << k)


// // 3. Set k-th Bit to 1
// num | (1 << k)


// // 4. Clear k-th Bit
// num & ~(1 << k)


// // 5. Toggle k-th Bit
// num ^ (1 << k)


// // 6. Remove the rightmost 1
// num & (num - 1)


// // 7. Check Power of Two
// num > 0 && (num & (num - 1)) == 0